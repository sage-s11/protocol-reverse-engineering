package com.pre.output;

import com.pre.core.AnalysisResult;
import com.pre.core.BoundaryResult;
import com.pre.core.FieldCandidate;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.Arrays;
import java.util.Arrays;
import java.util.List;
import java.util.stream.Collectors;

/**
 * Generates two output artifacts from an AnalysisResult:
 *   1. A working Java parser class
 *   2. A human-readable Markdown protocol specification
 */
public class Generator {

    public record OutputPaths(Path parser, Path spec) {}

    // ────────────────────────────────────────────────────────────────────────
    // Java parser generation
    // ────────────────────────────────────────────────────────────────────────

    public static String generateParser(AnalysisResult result, String protocolName) {
        String className = toClassName(protocolName) + "Parser";
        String msgClassName = toClassName(protocolName) + "Message";
        BoundaryResult b = result.boundary();
        String now = LocalDateTime.now().format(DateTimeFormatter.ISO_LOCAL_DATE_TIME);

        StringBuilder sb = new StringBuilder();
        sb.append("package com.pre.generated;\n\n");
        sb.append("import java.util.*;\n\n");
        sb.append("/**\n");
        sb.append(" * ").append(protocolName).append(" Parser\n");
        sb.append(" * Auto-generated by Protocol Reverse Engineering Engine\n");
        sb.append(" * Generated: ").append(now).append("\n");
        sb.append(" *\n");
        sb.append(" * Flow: ").append(result.flowKey()).append("\n");
        sb.append(" * Messages analysed: ").append(result.messageCount()).append("\n");
        sb.append(" * Boundary strategy: ").append(b.strategy().label)
                .append(" (confidence: ").append(String.format("%.0f%%", b.confidence() * 100)).append(")\n");
        sb.append(" */\n");
        sb.append("public class ").append(className).append(" {\n\n");

        // Magic constant
        if (b.magicBytes() != null) {
            sb.append("    private static final byte[] MAGIC = { ");
            for (int i = 0; i < b.magicBytes().length; i++) {
                if (i > 0) sb.append(", ");
                sb.append(String.format("(byte)0x%02X", b.magicBytes()[i]));
            }
            sb.append(" };\n\n");
        }

        // Message inner class
        sb.append("    public static class ").append(msgClassName).append(" {\n");
        sb.append("        public final byte[] raw;\n");
        sb.append("        public final List<String> parseErrors = new ArrayList<>();\n");
        for (FieldCandidate f : result.fields()) {
            String fieldName = toFieldName(f);
            String javaType = toJavaType(f);
            sb.append("        public ").append(javaType).append(" ")
                    .append(fieldName).append("; ")
                    .append("// offset=0x").append(String.format("%02x", f.offset()))
                    .append(" width=").append(f.width()).append("B")
                    .append(" conf=").append(String.format("%.0f%%", f.confidence() * 100))
                    .append("\n");
        }
        sb.append("\n");
        sb.append("        public ").append(msgClassName).append("(byte[] raw) { this.raw = raw; }\n\n");
        sb.append("        @Override public String toString() {\n");
        sb.append("            StringBuilder s = new StringBuilder(\"").append(msgClassName).append("{\\n\");\n");
        for (FieldCandidate f : result.fields()) {
            String fieldName = toFieldName(f);
            sb.append("            s.append(\"  ").append(fieldName)
                    .append(" = \").append(").append(fieldName).append(").append(\"\\n\");\n");
        }
        sb.append("            return s.append(\"}\").toString();\n");
        sb.append("        }\n");
        sb.append("    }\n\n");

        // parse() method
        sb.append("    public static ").append(msgClassName).append(" parse(byte[] data) {\n");
        sb.append("        ").append(msgClassName).append(" msg = new ").append(msgClassName).append("(data);\n");
        sb.append("        if (data.length < ").append(b.headerSize()).append(") {\n");
        sb.append("            msg.parseErrors.add(\"Packet too short: \" + data.length + \" < ").append(b.headerSize()).append("\");\n");
        sb.append("            return msg;\n");
        sb.append("        }\n\n");

        // Magic check
        if (b.magicBytes() != null) {
            sb.append("        // Validate magic header\n");
            sb.append("        for (int i = 0; i < MAGIC.length; i++) {\n");
            sb.append("            if (data[i] != MAGIC[i]) {\n");
            sb.append("                msg.parseErrors.add(\"Invalid magic at byte \" + i);\n");
            sb.append("            }\n");
            sb.append("        }\n\n");
        }

        // Field parsing
        for (FieldCandidate f : result.fields()) {
            sb.append(generateFieldParse(f));
        }

        sb.append("        return msg;\n");
        sb.append("    }\n\n");

        // parseAll() method
        sb.append("    public static List<").append(msgClassName).append("> parseAll(List<byte[]> payloads) {\n");
        sb.append("        List<").append(msgClassName).append("> results = new ArrayList<>();\n");
        sb.append("        for (byte[] p : payloads) results.add(parse(p));\n");
        sb.append("        return results;\n");
        sb.append("    }\n\n");

        // hexdump() utility
        sb.append("    public static String hexDump(byte[] data) {\n");
        sb.append("        StringBuilder sb = new StringBuilder();\n");
        sb.append("        for (int i = 0; i < data.length; i += 16) {\n");
        sb.append("            sb.append(String.format(\"%04x  \", i));\n");
        sb.append("            StringBuilder asc = new StringBuilder();\n");
        sb.append("            for (int j = i; j < Math.min(i + 16, data.length); j++) {\n");
        sb.append("                sb.append(String.format(\"%02x \", data[j]));\n");
        sb.append("                asc.append(data[j] >= 32 && data[j] < 127 ? (char) data[j] : '.');\n");
        sb.append("            }\n");
        sb.append("            sb.append(\" \").append(asc).append(\"\\n\");\n");
        sb.append("        }\n");
        sb.append("        return sb.toString();\n");
        sb.append("    }\n");
        sb.append("}\n");

        return sb.toString();
    }

    private static String generateFieldParse(FieldCandidate f) {
        String fieldName = toFieldName(f);
        int offset = f.offset();
        int end = offset + f.width();
        StringBuilder sb = new StringBuilder();
        sb.append("        try {\n");

        switch (f.typeHint()) {
            case "ipv4" -> sb.append(String.format(
                    "            msg.%s = String.format(\"%%d.%%d.%%d.%%d\"," +
                    " data[%d]&0xFF, data[%d]&0xFF, data[%d]&0xFF, data[%d]&0xFF);\n",
                    fieldName, offset, offset+1, offset+2, offset+3));
            case "uint8" -> sb.append(String.format(
                    "            msg.%s = data[%d] & 0xFF;\n", fieldName, offset));
            case "uint16", "uint16_be" -> sb.append(String.format(
                    "            msg.%s = ((data[%d] & 0xFF) << 8) | (data[%d] & 0xFF);\n",
                    fieldName, offset, offset+1));
            case "uint16_le" -> sb.append(String.format(
                    "            msg.%s = ((data[%d] & 0xFF) << 8) | (data[%d] & 0xFF);\n",
                    fieldName, offset+1, offset));
            case "uint32", "uint32_be", "timestamp_unix" -> sb.append(String.format(
                    "            msg.%s = ((long)(data[%d]&0xFF)<<24)|((long)(data[%d]&0xFF)<<16)|" +
                    "((long)(data[%d]&0xFF)<<8)|(data[%d]&0xFF);\n",
                    fieldName, offset, offset+1, offset+2, offset+3));
            case "uint32_le", "sequence_number" -> sb.append(String.format(
                    "            msg.%s = ((long)(data[%d]&0xFF)<<24)|((long)(data[%d]&0xFF)<<16)|" +
                    "((long)(data[%d]&0xFF)<<8)|(data[%d]&0xFF);\n",
                    fieldName, offset+3, offset+2, offset+1, offset));
            default -> sb.append(String.format(
                    "            msg.%s = java.util.Arrays.copyOfRange(data, %d, %d);\n",
                    fieldName, offset, end));
        }

        sb.append("        } catch (Exception e) {\n");
        sb.append("            msg.parseErrors.add(\"field_").append(String.format("%02x", offset))
                .append(": \" + e.getMessage());\n");
        sb.append("        }\n");
        return sb.toString();
    }

    // ────────────────────────────────────────────────────────────────────────
    // Markdown spec generation
    // ────────────────────────────────────────────────────────────────────────

    public static String generateSpec(AnalysisResult result, String protocolName) {
        BoundaryResult b = result.boundary();
        String now = LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss"));
        String magicStr = b.magicBytes() != null ? "`" + b.magicHex() + "`" : "None detected";
        String lengthStr = b.lengthFieldOffset() != null
                ? String.format("offset `0x%02x`, %dB", b.lengthFieldOffset(), b.lengthFieldWidth())
                : "None detected";

        String fieldTable = result.fields().stream().map(f -> {
            String vals = f.observedValues().stream().limit(4)
                    .map(v -> v instanceof Long l ? "0x" + Long.toHexString(l) : v.toString())
                    .collect(Collectors.joining(", "));
            return String.format("| `0x%02x` | %d | `%s` | %s | %.0f%% | %.2f | %s |",
                    f.offset(), f.width(), f.typeHint(), f.label(), f.confidence()*100, f.entropy(), vals);
        }).collect(Collectors.joining("\n"));

        String grammarLines = result.grammarNotes().stream()
                .map(n -> "- " + n).collect(Collectors.joining("\n"));
        String boundaryNotes = b.notes().stream()
                .map(n -> "- " + n).collect(Collectors.joining("\n"));

        return """
                # %s — Inferred Protocol Specification

                > **Auto-generated by Protocol Reverse Engineering Engine**
                > Generated: %s

                ---

                ## Overview

                | Property | Value |
                |---|---|
                | Flow | `%s` |
                | Messages analysed | %d |
                | Size range | %d – %d bytes (median: %d) |
                | Framing strategy | **%s** (confidence: %.0f%%) |
                | Magic header | %s |
                | Length field | %s |

                ---

                ## Framing

                %s

                ---

                ## Field Map

                | Offset | Width | Type | Inferred Label | Confidence | Entropy | Sample Values |
                |--------|-------|------|---------------|-----------|---------|---------------|
                %s

                > **Entropy guide:** 0.0 = constant · ~1.0 = enum/type · ~3.5+ = payload/random

                ---

                ## Grammar / Message Flow

                %s

                ---

                ## Usage (Java)

                ```java
                // Parse a single raw packet
                %sParser.%sMessage msg = %sParser.parse(rawBytes);
                System.out.println(msg);

                // Parse all payloads in a flow
                List<%sParser.%sMessage> messages = %sParser.parseAll(payloads);

                // Hexdump helper
                System.out.println(%sParser.hexDump(rawBytes));
                ```

                ---

                ## Confidence Guide

                - **≥ 80%%** — Reliable. High statistical certainty.
                - **50–79%%** — Probable. Verify with more samples.
                - **< 50%%** — Speculative. Treat as unknown until confirmed.

                Collect 50+ messages for best accuracy on unknown protocols.

                ---

                *This specification was statistically inferred and requires domain validation.*
                """.formatted(
                protocolName, now,
                result.flowKey(),
                result.messageCount(),
                result.minSize(), result.maxSize(), result.medianSize(),
                b.strategy().label, b.confidence() * 100,
                magicStr, lengthStr,
                boundaryNotes,
                fieldTable,
                grammarLines,
                toClassName(protocolName), toClassName(protocolName),
                toClassName(protocolName), toClassName(protocolName),
                toClassName(protocolName), toClassName(protocolName),
                toClassName(protocolName)
        );
    }

    // ────────────────────────────────────────────────────────────────────────
    // File I/O
    // ────────────────────────────────────────────────────────────────────────

    public static OutputPaths save(AnalysisResult result, String protocolName, Path outputDir)
            throws IOException {
        Path parsersDir = outputDir.resolve("parsers");
        Path specsDir   = outputDir.resolve("specs");
        Files.createDirectories(parsersDir);
        Files.createDirectories(specsDir);

        String safeName = protocolName.toLowerCase().replaceAll("[^a-z0-9]", "_");
        Path parserPath = parsersDir.resolve(safeName + "_parser.java");
        Path specPath   = specsDir.resolve(safeName + "_spec.md");

        Files.writeString(parserPath, generateParser(result, protocolName));
        Files.writeString(specPath,   generateSpec(result, protocolName));

        return new OutputPaths(parserPath, specPath);
    }

    // ────────────────────────────────────────────────────────────────────────
    // Naming helpers
    // ────────────────────────────────────────────────────────────────────────

    public static String toClassName(String name) {
        return Arrays.stream(name.replaceAll("[^a-zA-Z0-9]", "_").split("_"))
                .filter(s -> !s.isEmpty())
                .map(s -> Character.toUpperCase(s.charAt(0)) + s.substring(1).toLowerCase())
                .collect(Collectors.joining());
    }

    private static String toFieldName(FieldCandidate f) {
        String base = f.label()
                .replaceAll("[^a-zA-Z0-9 ]", "")
                .trim()
                .replaceAll("\\s+", "_")
                .toLowerCase();
        if (base.isEmpty()) base = "field";
        return "f" + String.format("%02x", f.offset()) + "_" + base;
    }

    private static String toJavaType(FieldCandidate f) {
        return switch (f.typeHint()) {
            case "ipv4"                        -> "String";
            case "uint8"                       -> "int";
            case "uint16", "uint16_be",
                 "uint16_le"                   -> "int";
            case "uint32", "uint32_be",
                 "uint32_le", "timestamp_unix",
                 "sequence_number"             -> "long";
            default                            -> "byte[]";
        };
    }
}
